ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DECOMP = os.path.expanduser("~/Code/decomp/yb-2026-11-13/full")
DEFAULT_RULES = os.path.join(ROOT, "tools", "vanilla_rules.json")

# ILSpy 8.x appends an update nag to its output when run with stdout captured into the file.
TRAILER_PATTERNS = (
    re.compile(r"^You are not using the latest version of the tool"),
    re.compile(r"^Latest version is '"),
)

HEADER_BEGIN = "// ==== COPIED GAME CODE: Junction Rules, JunctionRules/Vanilla/ ===="
HEADER_END = "// ==== end of header; the code below is the game's, changed only as listed in DEVIATIONS.md ===="

BLOCK_BEGIN = re.compile(r"^\s*// (?P<tag>[A-Z0-9-]+) BEGIN (?P<id>[A-Za-z0-9-]+)(?::.*)?$")
BLOCK_END = re.compile(r"^\s*// (?P<tag>[A-Z0-9-]+) END\s*$")
ANCHOR_LINES = 3


class RuleError(Exception):
    pass


def load_rules(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def normalise(text: str) -> str:
    """LF line ends, no trailing blanks, no ILSpy trailer, exactly one final newline."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.startswith("﻿"):
        text = text[1:]
    lines = [ln.rstrip() for ln in text.split("\n")]
    while lines and (lines[-1] == "" or any(p.match(lines[-1]) for p in TRAILER_PATTERNS)):
        lines.pop()
    return "\n".join(lines) + "\n"


def block_rules(rules: dict) -> dict:
    """{"tag": str, "blocks": {id: {"files": {target: count}, ...}}} or an empty spec."""
    mb = rules.get("marked_blocks") or {}
    return {"tag": mb.get("tag", "JR-STAGE2"), "blocks": mb.get("blocks", {})}


def file_block_ids(rules: dict, target: str) -> list[str]:
    return [i for i, b in block_rules(rules)["blocks"].items() if target in b.get("files", {})]


def header(rules: dict, file_rule: dict) -> str:
    mf = rules["made_from"]
    ids = [r["id"] for r in rules["renames"]] + [rules["namespace"]["id"]]
    ids += [d["id"] for d in rules["deviations"] if file_rule["target"] in (d.get("files") or {d.get("file"): 1})]
    lines = [
        HEADER_BEGIN,
        f"// Source: Game.dll {mf['game_full_version']} (sha256 {mf['game_dll_sha256']}),",
        f"//         decompiled with {mf['decompiler']} on {mf['decompiled_on']}.",
        f"// Original type: {file_rule['original_type']}.",
        "// This file is generated by tools/vanilla_copy.py from the decompile; do not edit it by hand. Change",
        "// tools/vanilla_rules.json (and DEVIATIONS.md) and run `python3 tools/vanilla_copy.py generate`.",
        f"// Changes applied: {', '.join(ids)} (see DEVIATIONS.md). Logic is otherwise the game's, unchanged.",
    ]
    bids = file_block_ids(rules, file_rule["target"])
    if bids:
        tag = block_rules(rules)["tag"]
        lines += [
            f"// Exception: hand-written code only inside '// {tag} BEGIN <id>' ... '// {tag} END' blocks",
            f"// ({', '.join(bids)}; see DEVIATIONS.md). `check` proves everything outside them is the above.",
        ]
    lines += [HEADER_END, ""]
    return "\n".join(lines) + "\n"


def split_blocks(text: str):
    """Copy text -> (text without blocks, blocks, errors). A block is (id, index in the stripped line list where it
    sat, its lines incl. markers)."""
    out, blocks, errors = [], [], []
    cur = None
    for n, ln in enumerate(text.split("\n"), 1):
        mb, me = BLOCK_BEGIN.match(ln), BLOCK_END.match(ln)
        if mb and mb.group("tag") != "COPIED":
            if cur is not None:
                errors.append(f"line {n}: block {mb.group('id')} begins inside block {cur[0]} (nesting not allowed)")
                cur[2].append(ln)
                continue
            cur = (mb.group("id"), len(out), [ln], mb.group("tag"))
            continue
        if me:
            if cur is None:
                errors.append(f"line {n}: END without BEGIN")
                continue
            if me.group("tag") != cur[3]:
                errors.append(f"line {n}: END tag {me.group('tag')} does not match BEGIN tag {cur[3]}")
            cur[2].append(ln)
            blocks.append((cur[0], cur[1], cur[2], cur[3]))
            cur = None
            continue
        if cur is not None:
            cur[2].append(ln)
        else:
            out.append(ln)
    if cur is not None:
        errors.append(f"block {cur[0]} has no END")
    return "\n".join(out), blocks, errors


def check_blocks(rules: dict, target: str, blocks, errors, require_all: bool = True) -> list[str]:
    """Problems with the blocks of one file (declaration, counts, tag)."""
    spec = block_rules(rules)
    problems = list(errors)
    seen = {}
    for bid, _pos, lines, tag in blocks:
        if tag != spec["tag"]:
            problems.append(f"block {bid}: tag {tag} is not {spec['tag']}")
        seen[bid] = seen.get(bid, 0) + 1
    for bid, n in seen.items():
        want = spec["blocks"].get(bid, {}).get("files", {}).get(target)
        if want is None:
            problems.append(f"block {bid} is not declared for {target} in the rules (marked_blocks)")
        elif want != n:
            problems.append(f"block {bid} occurs {n} times in {target} (rules say {want})")
    for bid in file_block_ids(rules, target):
        if require_all and bid not in seen:
            problems.append(f"block {bid} is declared for {target} but missing")
    return problems


def reinsert_blocks(generated: str, old_stripped: str, blocks) -> tuple[str, list[str]]:
    """Puts blocks back into freshly generated text after the same ANCHOR_LINES preceding lines."""
    old = old_stripped.split("\n")
    new = generated.split("\n")
    placed, errors = [], []
    for bid, pos, lines, _tag in blocks:
        ctx = old[max(0, pos - ANCHOR_LINES):pos]
        if len(ctx) < ANCHOR_LINES:
            errors.append(f"block {bid}: fewer than {ANCHOR_LINES} lines before it")
            continue
        hits = [i for i in range(len(new) - len(ctx) + 1) if new[i:i + len(ctx)] == ctx]
        if len(hits) != 1:
            errors.append(f"block {bid}: its {ANCHOR_LINES} preceding lines occur {len(hits)} times in the new text "
                          f"(need exactly 1); port it by hand")
            continue
        placed.append((hits[0] + len(ctx), lines))
    for at, lines in sorted(placed, key=lambda x: -x[0]):
        new[at:at] = lines
    return "\n".join(new), errors


def transform(source_text: str, rules: dict, file_rule: dict, stats: dict | None = None) -> str:
    """Decompiled source -> expected copy text. Raises RuleError when a rule does not apply as declared."""
    text = normalise(source_text)
    counts = {}

    # Renames: whole identifiers only.
    for r in rules["renames"]:
        pattern = re.compile(r"\b" + re.escape(r["from"]) + r"\b")
        text, n = pattern.subn(r["to"], text)
        counts[r["id"]] = n

    # Namespace move + usings that restore the original lookup.
    ns = rules["namespace"]
    lines = text.split("\n")
    idx = [i for i, ln in enumerate(lines) if ln == ns["from"]]
    if len(idx) != 1:
        raise RuleError(f"{ns['id']}: expected exactly one line '{ns['from']}' in {file_rule['source']}, found {len(idx)}")
    lines[idx[0]] = ns["to"]
    using_idx = [i for i, ln in enumerate(lines[: idx[0]]) if ln.startswith("using ")]
    insert_at = (using_idx[-1] + 1) if using_idx else idx[0]
    existing = set(lines[: idx[0]])
    added = [u for u in ns["add_usings"] if u not in existing]
    lines[insert_at:insert_at] = added
    counts[ns["id"]] = 1
    text = "\n".join(lines)

    # Deviations: find/replace (exact text, or a regex when "regex": true) with a declared occurrence count,
    # applied after renames. A deviation may list several files, each with its own count.
    for d in rules["deviations"]:
        per_file = d.get("files") or {d["file"]: d.get("count", 1)}
        if file_rule["target"] not in per_file:
            continue
        want = per_file[file_rule["target"]]
        if d.get("regex"):
            pattern = re.compile(d["find"])
            n = len(pattern.findall(text))
            if n == want:
                text = pattern.sub(d["replace"], text)
        else:
            n = text.count(d["find"])
            if n == want:
                text = text.replace(d["find"], d["replace"])
        if n != want:
            raise RuleError(f"{d['id']}: find {'pattern' if d.get('regex') else 'text'} occurs {n} times in "
                            f"{file_rule['source']} (rules say {want}); the decompile changed or the rule is wrong")
        counts[d["id"]] = n

    if stats is not None:
        stats.update(counts)
    return header(rules, file_rule) + text


def deviation_ids_documented(rules: dict, deviations_md: str) -> list[str]:
    """Rule ids that DEVIATIONS.md does not mention."""
    ids = [r["id"] for r in rules["renames"]] + [rules["namespace"]["id"]] + [d["id"] for d in rules["deviations"]]
    ids += list(block_rules(rules)["blocks"].keys())
    return [i for i in ids if not re.search(r"\b" + re.escape(i) + r"\b", deviations_md)]


def cmd_generate(args) -> int:
    rules = load_rules(args.rules)
    failed = 0
    for fr in rules["files"]:
        src = os.path.join(args.decomp, fr["source"])
        with open(src, encoding="utf-8-sig") as f:
            st = {}
            out = transform(f.read(), rules, fr, st)
        dst = os.path.join(args.root, fr["target"])
        kept = 0
        if os.path.exists(dst):
            with open(dst, encoding="utf-8") as f:
                stripped, blocks, errors = split_blocks(normalise(f.read()))
            errors += check_blocks(rules, fr["target"], blocks, [], require_all=False)
            if not errors:
                out, errors = reinsert_blocks(out, stripped, blocks)
            if errors:
                for e in errors:
                    print(f"BLOCK FAILURE {fr['target']}: {e}")
                print(f"NOT WRITTEN {fr['target']}")
                failed += 1
                continue
            kept = len(blocks)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print(f"wrote {fr['target']} ({out.count(chr(10))} lines; rule hits {st}; marked blocks kept {kept})")
    return 0 if failed == 0 else 1


def cmd_check(args) -> int:
    rules = load_rules(args.rules)
    problems = 0
    total_src_lines = 0
    total_blocks = 0
    total_inner = 0
    for fr in rules["files"]:
        src = os.path.join(args.decomp, fr["source"])
        dst = os.path.join(args.root, fr["target"])
        with open(src, encoding="utf-8-sig") as f:
            src_text = f.read()
        total_src_lines += normalise(src_text).count("\n")
        st = {}
        try:
            expected = transform(src_text, rules, fr, st)
        except RuleError as e:
            print(f"RULE FAILURE: {e}")
            problems += 1
            continue
        if not os.path.exists(dst):
            print(f"MISSING: {fr['target']}")
            problems += 1
            continue
        with open(dst, encoding="utf-8") as f:
            actual, blocks, errors = split_blocks(normalise(f.read()))
        bprob = check_blocks(rules, fr["target"], blocks, errors)
        for e in bprob:
            print(f"BLOCK {fr['target']}: {e}")
        problems += len(bprob)
        inner = sum(len(b[2]) - 2 for b in blocks)
        total_blocks += len(blocks)
        total_inner += inner
        binfo = f"; marked blocks {len(blocks)} with {inner} lines inside (markers excluded)"
        if actual == expected:
            print(f"OK   {fr['target']}: outside marked blocks equals {fr['source']} + rules (rule hits {st}{binfo})")
            continue
        diff = list(difflib.unified_diff(expected.split("\n"), actual.split("\n"),
                                         fromfile=f"expected (decompile + rules) {fr['source']}",
                                         tofile=f"copy {fr['target']}", lineterm="", n=2))
        hunks = sum(1 for ln in diff if ln.startswith("@@"))
        print(f"DIFF {fr['target']}: {hunks} unexplained difference block(s)")
        for ln in diff[: args.max_lines]:
            print("  " + ln)
        if len(diff) > args.max_lines:
            print(f"  ... {len(diff) - args.max_lines} more diff lines")
        problems += hunks
    dev_md = os.path.join(args.root, "DEVIATIONS.md")
    if os.path.exists(dev_md):
        with open(dev_md, encoding="utf-8") as f:
            missing = deviation_ids_documented(rules, f.read())
        for i in missing:
            print(f"UNDOCUMENTED: rule {i} is not described in DEVIATIONS.md")
        problems += len(missing)
    else:
        print("UNDOCUMENTED: DEVIATIONS.md not found")
        problems += 1
    print(f"decompiled lines copied: {total_src_lines}; documented deviations: {len(rules['deviations'])}; "
          f"marked blocks: {total_blocks} ({total_inner} lines inside); unexplained differences: {problems}")
    return 0 if problems == 0 else 1


def cmd_compare_decomp(args) -> int:
    rules = load_rules(args.rules)
    changed = 0
    for fr in rules["files"]:
        a = os.path.join(args.old, fr["source"])
        b = os.path.join(args.new, fr["source"])
        with open(a, encoding="utf-8-sig") as f:
            ta = normalise(f.read())
        with open(b, encoding="utf-8-sig") as f:
            tb = normalise(f.read())
        if ta == tb:
            print(f"SAME    {fr['source']}")
            continue
        changed += 1
        diff = list(difflib.unified_diff(ta.split("\n"), tb.split("\n"), fromfile="old/" + fr["source"],
                                         tofile="new/" + fr["source"], lineterm="", n=2))
        print(f"CHANGED {fr['source']} ({sum(1 for ln in diff if ln.startswith('@@'))} block(s))")
        for ln in diff[: args.max_lines]:
            print("  " + ln)
    return 0 if changed == 0 else 2


