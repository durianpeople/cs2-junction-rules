#!/usr/bin/env python3
"""Make and verify the copy of the game's car-driving code in JunctionRules/Vanilla/.

The copy must equal "ILSpy decompile of Game.dll + the rules in tools/vanilla_rules.json" and nothing else.
The rules are: type renames, a namespace move (plus the usings that restore the original name lookup), and
explicit find/replace deviations, each with an id that DEVIATIONS.md must explain.

Commands (all paths default to this repository and the 13 Nov 2026 decompile):
  check            prove the copy equals decompile + rules; exit 1 on any unexplained difference
  generate         (re)write the copy from the decompile + rules (use after a game patch, then build and test)
  compare-decomp   OLD_DIR NEW_DIR: diff the copied types between two decompiles (patch triage)
  selftest         self-test of this script on temporary files (no repository files touched)

Typical patch workflow: decompile the new Game.dll (ilspycmd -p -o NEW Game.dll), run
`compare-decomp OLD NEW`; if the types changed, run `generate --decomp NEW`, port any deviation whose find
text no longer matches (generate reports it), rebuild, update made_from and the version gate constants.
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DECOMP = os.path.expanduser("~/Code/decomp/yb-2026-11-13/full")
DEFAULT_RULES = os.path.join(ROOT, "tools", "vanilla_rules.json")

# ILSpy 8.x appends an update nag to its output when run with stdout captured into the file.
TRAILER_PATTERNS = (
    re.compile(r"^You are not using the latest version of the tool"),
    re.compile(r"^Latest version is '"),
)

HEADER_BEGIN = "// ==== COPIED GAME CODE: Junction Rules, JunctionRules/Vanilla/ ===="
HEADER_END = "// ==== end of header; the code below is the game's, changed only as listed in DEVIATIONS.md ===="


class RuleError(Exception):
    pass


def load_rules(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def normalise(text: str) -> str:
    """LF line ends, no trailing blanks, no ILSpy trailer, exactly one final newline."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.startswith("﻿"):
        text = text[1:]
    lines = [ln.rstrip() for ln in text.split("\n")]
    while lines and (lines[-1] == "" or any(p.match(lines[-1]) for p in TRAILER_PATTERNS)):
        lines.pop()
    return "\n".join(lines) + "\n"


def header(rules: dict, file_rule: dict) -> str:
    mf = rules["made_from"]
    ids = [r["id"] for r in rules["renames"]] + [rules["namespace"]["id"]]
    ids += [d["id"] for d in rules["deviations"] if file_rule["target"] in (d.get("files") or {d.get("file"): 1})]
    return "\n".join([
        HEADER_BEGIN,
        f"// Source: Game.dll {mf['game_full_version']} (sha256 {mf['game_dll_sha256']}),",
        f"//         decompiled with {mf['decompiler']} on {mf['decompiled_on']}.",
        f"// Original type: {file_rule['original_type']}.",
        "// This file is generated by tools/vanilla_copy.py from the decompile; do not edit it by hand. Change",
        "// tools/vanilla_rules.json (and DEVIATIONS.md) and run `python3 tools/vanilla_copy.py generate`.",
        f"// Changes applied: {', '.join(ids)} (see DEVIATIONS.md). Logic is otherwise the game's, unchanged.",
        HEADER_END,
        "",
    ]) + "\n"


def transform(source_text: str, rules: dict, file_rule: dict, stats: dict | None = None) -> str:
    """Decompiled source -> expected copy text. Raises RuleError when a rule does not apply as declared."""
    text = normalise(source_text)
    counts = {}

    # Renames: whole identifiers only.
    for r in rules["renames"]:
        pattern = re.compile(r"\b" + re.escape(r["from"]) + r"\b")
        text, n = pattern.subn(r["to"], text)
        counts[r["id"]] = n

    # Namespace move + usings that restore the original lookup.
    ns = rules["namespace"]
    lines = text.split("\n")
    idx = [i for i, ln in enumerate(lines) if ln == ns["from"]]
    if len(idx) != 1:
        raise RuleError(f"{ns['id']}: expected exactly one line '{ns['from']}' in {file_rule['source']}, found {len(idx)}")
    lines[idx[0]] = ns["to"]
    using_idx = [i for i, ln in enumerate(lines[: idx[0]]) if ln.startswith("using ")]
    insert_at = (using_idx[-1] + 1) if using_idx else idx[0]
    existing = set(lines[: idx[0]])
    added = [u for u in ns["add_usings"] if u not in existing]
    lines[insert_at:insert_at] = added
    counts[ns["id"]] = 1
    text = "\n".join(lines)

    # Deviations: find/replace (exact text, or a regex when "regex": true) with a declared occurrence count,
    # applied after renames. A deviation may list several files, each with its own count.
    for d in rules["deviations"]:
        per_file = d.get("files") or {d["file"]: d.get("count", 1)}
        if file_rule["target"] not in per_file:
            continue
        want = per_file[file_rule["target"]]
        if d.get("regex"):
            pattern = re.compile(d["find"])
            n = len(pattern.findall(text))
            if n == want:
                text = pattern.sub(d["replace"], text)
        else:
            n = text.count(d["find"])
            if n == want:
                text = text.replace(d["find"], d["replace"])
        if n != want:
            raise RuleError(f"{d['id']}: find {'pattern' if d.get('regex') else 'text'} occurs {n} times in "
                            f"{file_rule['source']} (rules say {want}); the decompile changed or the rule is wrong")
        counts[d["id"]] = n

    if stats is not None:
        stats.update(counts)
    return header(rules, file_rule) + text


def deviation_ids_documented(rules: dict, deviations_md: str) -> list[str]:
    """Rule ids that DEVIATIONS.md does not mention."""
    ids = [r["id"] for r in rules["renames"]] + [rules["namespace"]["id"]] + [d["id"] for d in rules["deviations"]]
    return [i for i in ids if not re.search(r"\b" + re.escape(i) + r"\b", deviations_md)]


def cmd_generate(args) -> int:
    rules = load_rules(args.rules)
    for fr in rules["files"]:
        src = os.path.join(args.decomp, fr["source"])
        with open(src, encoding="utf-8-sig") as f:
            st = {}
            out = transform(f.read(), rules, fr, st)
        dst = os.path.join(args.root, fr["target"])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
        print(f"wrote {fr['target']} ({out.count(chr(10))} lines; rule hits {st})")
    return 0


def cmd_check(args) -> int:
    rules = load_rules(args.rules)
    problems = 0
    total_src_lines = 0
    for fr in rules["files"]:
        src = os.path.join(args.decomp, fr["source"])
        dst = os.path.join(args.root, fr["target"])
        with open(src, encoding="utf-8-sig") as f:
            src_text = f.read()
        total_src_lines += normalise(src_text).count("\n")
        st = {}
        try:
            expected = transform(src_text, rules, fr, st)
        except RuleError as e:
            print(f"RULE FAILURE: {e}")
            problems += 1
            continue
        if not os.path.exists(dst):
            print(f"MISSING: {fr['target']}")
            problems += 1
            continue
        with open(dst, encoding="utf-8") as f:
            actual = normalise(f.read())
        if actual == expected:
            print(f"OK   {fr['target']}: equals {fr['source']} + rules (rule hits {st})")
            continue
        diff = list(difflib.unified_diff(expected.split("\n"), actual.split("\n"),
                                         fromfile=f"expected (decompile + rules) {fr['source']}",
                                         tofile=f"copy {fr['target']}", lineterm="", n=2))
        hunks = sum(1 for ln in diff if ln.startswith("@@"))
        print(f"DIFF {fr['target']}: {hunks} unexplained difference block(s)")
        for ln in diff[: args.max_lines]:
            print("  " + ln)
        if len(diff) > args.max_lines:
            print(f"  ... {len(diff) - args.max_lines} more diff lines")
        problems += hunks
    dev_md = os.path.join(args.root, "DEVIATIONS.md")
    if os.path.exists(dev_md):
        with open(dev_md, encoding="utf-8") as f:
            missing = deviation_ids_documented(rules, f.read())
        for i in missing:
            print(f"UNDOCUMENTED: rule {i} is not described in DEVIATIONS.md")
        problems += len(missing)
    else:
        print("UNDOCUMENTED: DEVIATIONS.md not found")
        problems += 1
    print(f"decompiled lines copied: {total_src_lines}; documented deviations: {len(rules['deviations'])}; "
          f"unexplained differences: {problems}")
    return 0 if problems == 0 else 1


def cmd_compare_decomp(args) -> int:
    rules = load_rules(args.rules)
    changed = 0
    for fr in rules["files"]:
        a = os.path.join(args.old, fr["source"])
        b = os.path.join(args.new, fr["source"])
        with open(a, encoding="utf-8-sig") as f:
            ta = normalise(f.read())
        with open(b, encoding="utf-8-sig") as f:
            tb = normalise(f.read())
        if ta == tb:
            print(f"SAME    {fr['source']}")
            continue
        changed += 1
        diff = list(difflib.unified_diff(ta.split("\n"), tb.split("\n"), fromfile="old/" + fr["source"],
                                         tofile="new/" + fr["source"], lineterm="", n=2))
        print(f"CHANGED {fr['source']} ({sum(1 for ln in diff if ln.startswith('@@'))} block(s))")
        for ln in diff[: args.max_lines]:
            print("  " + ln)
    return 0 if changed == 0 else 2


def cmd_selftest(_args) -> int:
    failures = 0

    def expect(cond: bool, name: str):
        nonlocal failures
        print(("pass " if cond else "FAIL ") + name)
        if not cond:
            failures += 1

    src = (
        "using Unity.Entities;\n\nnamespace Game.Simulation;\n\npublic class CarNavigationSystem : GameSystemBase\n{\n"
        "\tprivate CarLaneSpeedIterator m_It;\n\tprivate CarNavigationSystemX m_NotMe;\n\tint x = 1;   \n\tfloat y = 0f - z;\n\tfloat w = 10f - z;\n}\n"
        "You are not using the latest version of the tool, please update.\nLatest version is '11.2.0.10050'\n"
    )
    rules = {
        "made_from": {"game_full_version": "9.9.9f9 (1.1) [1.1]", "game_dll_sha256": "00", "decompiler": "t",
                      "decompiled_on": "today"},
        "files": [{"source": "A.cs", "target": "out/B.cs", "original_type": "Game.Simulation.CarNavigationSystem"}],
        "renames": [{"id": "R-01", "from": "CarNavigationSystem", "to": "JRCarNavigationSystem"},
                    {"id": "R-02", "from": "CarLaneSpeedIterator", "to": "JRCarLaneSpeedIterator"}],
        "namespace": {"id": "R-03", "from": "namespace Game.Simulation;", "to": "namespace JunctionRules.Vanilla;",
                      "add_usings": ["using Game;", "using Game.Simulation;"]},
        "deviations": [{"id": "D-01", "file": "out/B.cs", "find": "int x = 1;", "replace": "int x = 2;", "count": 1},
                       {"id": "D-02", "files": {"out/B.cs": 1}, "regex": True, "find": r"(= )0f - ", "replace": r"\1-"}],
    }
    tmp = tempfile.mkdtemp(prefix="vanilla_copy_selftest_")
    try:
        decomp = os.path.join(tmp, "decomp")
        root = os.path.join(tmp, "repo")
        os.makedirs(decomp)
        os.makedirs(os.path.join(root, "tools"))
        with open(os.path.join(decomp, "A.cs"), "w") as f:
            f.write(src)
        rpath = os.path.join(root, "tools", "rules.json")
        with open(rpath, "w") as f:
            json.dump(rules, f)
        with open(os.path.join(root, "DEVIATIONS.md"), "w") as f:
            f.write("R-01 R-02 R-03 D-01 D-02\n")
        ns = argparse.Namespace(decomp=decomp, rules=rpath, root=root, max_lines=50)

        out = transform(src, rules, rules["files"][0])
        expect("JRCarNavigationSystem : GameSystemBase" in out, "rename applies to whole identifier")
        expect("CarNavigationSystemX" in out and "JRCarNavigationSystemX" not in out, "rename leaves longer identifiers alone")
        expect("JRCarLaneSpeedIterator m_It" in out, "second rename applies")
        expect("namespace JunctionRules.Vanilla;" in out and "namespace Game.Simulation;" not in out, "namespace moved")
        expect(out.index("using Game.Simulation;") < out.index("namespace JunctionRules.Vanilla;"), "usings inserted before namespace")
        expect("int x = 2;" in out, "deviation applied")
        expect("float y = -z;" in out and "float w = 10f - z;" in out, "regex deviation applied only where declared")
        expect("latest version" not in out, "ILSpy trailer stripped")
        expect(out.startswith(HEADER_BEGIN), "source header added")

        devnull = open(os.devnull, "w")
        old = sys.stdout
        try:
            sys.stdout = devnull
            cmd_generate(ns)
            ok_clean = cmd_check(ns) == 0
            target = os.path.join(root, "out", "B.cs")
            with open(target) as f:
                good = f.read()
            with open(target, "w") as f:
                f.write(good.replace("int x = 2;", "int x = 3;"))
            ok_planted = cmd_check(ns) == 1
            with open(target, "w") as f:
                f.write(good.replace("\n", "\r\n").replace("int x = 2;", "int x = 2;   "))
            ok_ws = cmd_check(ns) == 0
            with open(target, "w") as f:
                f.write(good)
            with open(os.path.join(root, "DEVIATIONS.md"), "w") as f:
                f.write("R-01 R-02 R-03 D-02\n")
            ok_undoc = cmd_check(ns) == 1
            with open(os.path.join(root, "DEVIATIONS.md"), "w") as f:
                f.write("R-01 R-02 R-03 D-01 D-02\n")
            rules["deviations"][0]["find"] = "int y = 1;"
            with open(rpath, "w") as f:
                json.dump(rules, f)
            ok_stale = cmd_check(ns) == 1
            rules["deviations"][0]["find"] = "int x = 1;"
            with open(rpath, "w") as f:
                json.dump(rules, f)
            os.makedirs(os.path.join(tmp, "new"))
            with open(os.path.join(tmp, "new", "A.cs"), "w") as f:
                f.write(src)
            same = cmd_compare_decomp(argparse.Namespace(rules=rpath, old=decomp, new=os.path.join(tmp, "new"), max_lines=5)) == 0
            with open(os.path.join(tmp, "new", "A.cs"), "w") as f:
                f.write(src.replace("int x = 1;", "int x = 5;"))
            changed = cmd_compare_decomp(argparse.Namespace(rules=rpath, old=decomp, new=os.path.join(tmp, "new"), max_lines=5)) == 2
        finally:
            sys.stdout = old
            devnull.close()
        expect(ok_clean, "check: generated copy has zero unexplained differences")
        expect(ok_planted, "check: a planted logic change is reported")
        expect(ok_ws, "check: CRLF and trailing blanks are not differences")
        expect(ok_undoc, "check: a rule missing from DEVIATIONS.md is reported")
        expect(ok_stale, "check: a deviation whose find text no longer matches is reported")
        expect(same, "compare-decomp: identical decompiles report SAME")
        expect(changed, "compare-decomp: a changed decompile is reported")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print(f"selftest: {'OK' if failures == 0 else str(failures) + ' failure(s)'}")
    return 0 if failures == 0 else 1


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--rules", default=DEFAULT_RULES)
    p.add_argument("--root", default=ROOT, help="repository root (targets are relative to it)")
    p.add_argument("--max-lines", type=int, default=200, help="diff lines to print per file")
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("check", "generate"):
        sp = sub.add_parser(name)
        sp.add_argument("--decomp", default=DEFAULT_DECOMP, help="ILSpy project output of Game.dll (has Game.Simulation/)")
    sp = sub.add_parser("compare-decomp")
    sp.add_argument("old")
    sp.add_argument("new")
    sub.add_parser("selftest")
    args = p.parse_args(argv)
    return {"check": cmd_check, "generate": cmd_generate, "compare-decomp": cmd_compare_decomp,
            "selftest": cmd_selftest}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
